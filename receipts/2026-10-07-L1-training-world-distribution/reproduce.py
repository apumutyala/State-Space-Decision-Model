"""Regenerate both synthetic cohorts into a fresh directory, without models."""

import argparse
import hashlib
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from language_growth.multirecord_data import (  # noqa: E402
    MULTIWORLD_COUNT, MULTIWORLD_SEED, MULTIWORLD_TRAIN_SPLIT,
    MULTIWORLD_VALIDATION_SPLIT, _json, generate_multirecord_tasks,
    multirecord_manifest, multirecord_rows,
)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=False)
    source = Path(__file__).resolve().parent
    for split in (MULTIWORLD_TRAIN_SPLIT, MULTIWORLD_VALIDATION_SPLIT):
        tasks = generate_multirecord_tasks(MULTIWORLD_SEED, MULTIWORLD_COUNT, split=split)
        for suffix, data in ((".jsonl", multirecord_rows(tasks)),
                             ("-manifest.json", _json(multirecord_manifest(tasks)) + b"\n")):
            name = split + suffix
            if data != (source / name).read_bytes():
                raise ValueError(f"regenerated bytes differ: {name}")
            (args.out / name).write_bytes(data)
            print(name, len(data), hashlib.sha256(data).hexdigest())


if __name__ == "__main__":
    main()
