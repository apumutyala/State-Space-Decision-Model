class Checker:
    """The B1 ``Filter`` acceptance minus the K/T step (done by scripts/b_schema_tokcheck.py on both templates), with
    source-item reuse allowed up to ``MAX_REUSE`` and key-free-text near-duplicates allowed only WITHIN one source
    item (variants of one item share option texts by design); exact content duplicates are never allowed."""

    def __init__(self, ex: dict):
        from train.cohort_v3 import _ensure_kit
        from .build import content_guard
        from . import b1_check

        _ensure_kit()
        from harness.heldout import check_record
        self.check_record = check_record
        self.guard, self.guard_identity = content_guard()
        self.ex = ex
        self.b1c = b1_check
        self.index = b1_check.build_index(config.DATA_ROOT)
        self.templates = b1_check.instruction_templates()
        self.content: set[int] = set()
        self.text_owner: dict[int, int] = {}  # key-free text key -> source-item hash that owns it
        self.reasons: dict[str, collections.Counter] = collections.defaultdict(collections.Counter)
        self.hit_examples: list = []

    def why_not(self, rec: dict, item_h: int) -> str | None:
        from train.cohort import record_content_hash, record_text_keys
        from train.guard import ForbiddenRow
        from . import augment as A, injection as I
        from .b1 import dedup_keys

        try:
            A.validate(rec)
            I.assert_no_heldout(rec["state"], rec["questions"], rec["id"])
        except AssertionError:
            return "structure_or_d1_template"
        items = root_items(rec)
        ch, tk = record_content_hash(rec), record_text_keys(rec)
        if rec["id"] in self.ex["ids"] or items & self.ex["items"]:
            return "cohort_id_or_item"
        if ch in self.ex["content"]:
            return "cohort_content"
        if tk & self.ex["text"]:
            return "cohort_text"
        if h64(ch) in self.content:
            return "dup_content"
        dk = [h64(k) for k in dedup_keys(rec)]
        if any(self.text_owner.get(k, item_h) != item_h for k in dk):
            return "dup_text_other_item"
        try:
            self.guard.check(rec)
        except ForbiddenRow:
            return "splitguard"
        try:
            self.check_record(rec)
        except Exception:
            return "frozen_family"
        if ch in self.index["content"]:
            return "index_content"
        if tk & self.index["text"]:
            return "index_text"
        hits = [x for x in self.b1c.item_hits(rec, self.index, self.templates) if not x[3]]
        if hits:
            if len(self.hit_examples) < 10:
                self.hit_examples.append((rec["id"], hits[0][1], hits[0][2][:120]))
            return "index_item_text"
        return None

    def accept(self, rec: dict, fam: str, item_h: int) -> bool:
        from train.cohort import record_content_hash
        from .b1 import dedup_keys
        why = self.why_not(rec, item_h)
        self.reasons[fam][why or "kept"] += 1
        if why is None:
            self.content.add(h64(record_content_hash(rec)))
            for k in dedup_keys(rec):
                self.text_owner.setdefault(h64(k), item_h)
        return why is None


