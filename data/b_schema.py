def ids_referenced(rec: dict, ids: list[str], qcrit: dict | None = None) -> bool:
    """True when the record's text names the option ids (re-styling them would break the text)."""
    text = "\n".join(all_strings(rec["state"])) + "\n" + "\n".join(
        q["instructions"] for q in rec["questions"].values() if isinstance(q.get("instructions"), str))
    short = [i for i in ids if len(i) <= 2]
    if GEN["version"] >= 2 and qcrit is not None:
        opt_text = "\n".join(str(d) for d in qcrit.values() if d is not None)
        if AGGREGATE.search(opt_text):
            return True
        if short and re.search(r"(?<![\w])(" + "|".join(re.escape(i) for i in short) + r")\s*(?:,|and|or|&)\s*("
                               + "|".join(re.escape(i) for i in short) + r")(?![\w])", opt_text):
            return True
    if len(short) >= 2:
        pat = re.compile(r"(?:^|[\s(\[])(" + "|".join(re.escape(i) for i in short) + r")[.):\]]", re.M)
        if len(set(pat.findall(text))) >= 2:
            return True
    for i in ids:
        if len(i) > 2 and re.search(r"(?<![\w])" + re.escape(i) + r"(?![\w])", text, re.I):
            return True
    return False


def new_ids(style: str, k: int, rng: random.Random, old: list[str]) -> list[str] | None:
    if style == "letters":
        return [_letters(i) for i in range(k)]
    if style == "letters_lower":
        return [_letters(i).lower() for i in range(k)]
    if style in ("digits", "digits1"):
        start = 0 if style == "digits" else 1
        w = len(str(k - 1 + start)) if (GEN["version"] >= 2 and k > 10) else 0
        return [str(i + start).zfill(w) for i in range(k)]
    if style == "option_k":
        return [f"option_{i}" for i in range(k)]
    if style == "opaque":
        out: list[str] = []
        while len(set(out)) < k:
            out = [f"k_{rng.getrandbits(32):08x}" for _ in range(k)]
        return out
    if style == "words":
        return rng.sample(WORDS, k) if k <= len(WORDS) else None
    return list(old)  # keep


def relabel(q: dict, gold: str, rng: random.Random, style: str, keep_order: bool = False) -> tuple[dict, str]:
    """Choice question re-styled; the gold lands at a uniformly drawn canonical (sorted-id) position."""
    from decide.schema import canonical_options

    opts = list(q["criteria"].items())
    k = len(opts)
    ids = new_ids(style, k, rng, [o for o, _ in opts])
    if ids is None:
        ids, style = new_ids("letters", k, rng, []), "letters"
    if style == "keep":
        crit = dict(opts)
        rng.shuffle(opts)
        return {**q, "criteria": {o: crit[o] for o, _ in opts}}, gold
    # an option without a description: its id was its content -> keep it as the description
    opts = [(o, d if (d is not None and d != "") else o) for o, d in opts]
    g = next(o for o in opts if o[0] == gold)
    others = [o for o in opts if o[0] != gold]
    rng.shuffle(others)
    canon = [oid for oid, _ in canonical_options({"type": "choice", "criteria": {i: None for i in ids}})]
    pos = rng.randrange(k)
    seq = others[:pos] + [g] + others[pos:]
    crit = {canon[j]: seq[j][1] for j in range(k)}
    order = list(crit)
    rng.shuffle(order)  # dict (listing) order is irrelevant to the renderer; shuffled for raw-JSON consumers
    return {**q, "criteria": {o: crit[o] for o in order}}, canon[pos]


def shrink(q: dict, gold: str, rng: random.Random) -> dict | None:
    crit = q["criteria"]
    k = len(crit)
    if k < 3 or any(AGGREGATE.search(str(d)) for d in crit.values() if d is not None):
        return None
    keep = {gold} | {o for o, d in crit.items() if ABSTAIN.search(f"{o} {d or ''}")}
    rest = [o for o in crit if o not in keep]
    k_new = rng.randint(max(2, len(keep)), k - 1)
    n_rest = k_new - len(keep)
    if n_rest < 0 or n_rest >= len(rest):
        return None
    pick = set(rng.sample(rest, n_rest)) | keep
    return {**q, "criteria": {o: d for o, d in crit.items() if o in pick}}


def expand(q: dict, inventory: list[str], rng: random.Random) -> dict | None:
    crit = q["criteria"]
    have = {str(d).strip().casefold() for d in crit.values()}
    pool = [x for x in inventory if x.strip().casefold() not in have]
    k = len(crit)
    k_new = rng.choice([rng.randint(k + 1, max(k + 1, 16)), rng.randint(17, 40)]) if k < 40 else k
    add = k_new - k
    if add <= 0 or len(pool) < add:
        return None
    crit = dict(crit)
    used = set(crit)
    for i, d in enumerate(rng.sample(pool, add)):
        oid = f"__add_{i}"
        while oid in used:
            oid += "_"
        crit[oid] = d
        used.add(oid)
    return {**q, "criteria": crit}  # ids are re-styled right after (relabel), so __add_ ids never ship


def switch_type(q: dict, gold: str, rng: random.Random) -> tuple[dict, str] | None:
    from decide.schema import NOUL_DEFAULT_CRITERIA
    if q["type"] == "noul":
        c = {**NOUL_DEFAULT_CRITERIA, **(q.get("criteria") or {})}
        y, n = rng.choice(YESNO_PAIRS)
        crit = {y: c["true"], n: c["false"]}
        return {"type": "choice", "instructions": q.get("instructions"), "criteria": crit}, (y if gold == "true" else n)
    crit = q.get("criteria")
    if q["type"] != "choice" or not isinstance(crit, dict) or len(crit) != 2:
        return None
    low = {str(o).casefold(): o for o in crit}
    for y, n in (YESNO_PAIRS if GEN["version"] == 1 else BOOLEAN_PAIRS_V2):
        if set(low) == {y.casefold(), n.casefold()}:
            dy, dn = crit[low[y.casefold()]], crit[low[n.casefold()]]
            nq = {"type": "noul", "instructions": q.get("instructions")}
            if dy or dn:
                nq["criteria"] = {"true": dy or "Yes.", "false": dn or "No."}
            return nq, ("true" if gold == low[y.casefold()] else "false")
    return None


def paraphrase(instr: Any, qtype: str, rng: random.Random) -> tuple[Any, str | None]:
    from .augment import INSTR
    if not isinstance(instr, str) or not instr.strip():
        return instr, None
    for fam, lst in INSTR.items():
        if instr in lst and rng.random() < 0.6:
            alt = [t for t in lst if t != instr]
            return rng.choice(alt), f"instr_swap:{fam}"
    suffixes = SUFFIX_NOUL if qtype == "noul" else SUFFIX_SCORE if qtype == "score" else SUFFIX_CHOICE
    mode = rng.choice(("prefix", "suffix", "both"))
    out = instr
    if mode in ("prefix", "both"):
        out = rng.choice(PREFIXES) + out
    if mode in ("suffix", "both"):
        out = out + rng.choice(suffixes)
    return out, f"instr_frame:{mode}"


def case_style(key: str, style: str) -> str:
    parts = [p for p in re.split(r"[_\-\s]+|(?<=[a-z])(?=[A-Z])", key) if p]
    if not parts:
        return key
    if style == "camel":
        return parts[0].lower() + "".join(p[:1].upper() + p[1:].lower() for p in parts[1:])
    if style == "title":
        return " ".join(p[:1].upper() + p[1:].lower() for p in parts)
    if style == "upper":
        return "_".join(p.upper() for p in parts)
    if style == "kebab":
        return "-".join(p.lower() for p in parts)
    return "_".join(p.lower() for p in parts)


def _synonyms() -> dict[str, list[str]]:
    from .augment import FIELD_SYNONYMS
    out: dict[str, set[str]] = collections.defaultdict(set)
    for k, lst in FIELD_SYNONYMS.items():
        group = {k, *lst}
        for x in group:
            out[x] |= group
    return {k: sorted(v - CONTEXT_KEYS) for k, v in out.items()}


SYN = None


def rename_keys(keys: list[str], rng: random.Random) -> dict[str, str]:
    global SYN
    SYN = SYN or _synonyms()
    style = rng.choice(("snake", "camel", "title", "upper", "kebab"))
    out, used = {}, set()
    for k in keys:
        cands = [s for s in SYN.get(k, []) if s != k] if rng.random() < 0.6 else []
        nk = case_style(rng.choice(cands) if cands else k, style)
        while nk in used or not nk:
            nk = nk + "_" if nk else "field"
        used.add(nk)
        out[k] = nk
    return out


def as_text(fields: list[tuple[str, Any]], layout: str) -> str:
    lines = []
    for k, v in fields:
        v = v if isinstance(v, str) else canonical(v)
        name = case_style(k, "title")
        if layout == "colon":
            lines.append(f"{name}: {v}")
        elif layout == "bracket":
            lines.append(f"[{name}]\n{v}")
        elif layout == "tag":
            lines.append(f"<{case_style(k, 'snake')}>{v}</{case_style(k, 'snake')}>")
        else:
            lines.append(f"## {name}\n{v}")
    return "\n".join(lines)


def transform_state(state: Any, rng: random.Random) -> tuple[Any, str | None]:
    from .b1 import tool_field
    if isinstance(state, str):
        if not state.strip():
            return state, None
        if rng.random() < 0.7:
            return {rng.choice(STRING_WRAPS): state}, "state_wrap_string"
        return f"{rng.choice(('INPUT', 'STATE', 'CONTEXT', 'Input'))}:\n{state}", "state_header"
    if not isinstance(state, dict) or not state:
        return state, None
    tf = tool_field(state)
    ctx = {k for k in state if k in CONTEXT_KEYS or k == tf}
    free = [k for k in state if k not in ctx]
    if not free:
        return state, None
    order = list(free)
    rng.shuffle(order)
    modes = ["rename", "nest"] + (["list", "text"] if not ctx else [])
    mode = rng.choice(modes)
    if mode == "rename":
        ren = rename_keys(order, rng)
        out = {ren[k]: state[k] for k in order}
        out.update({k: state[k] for k in ctx})
        return out, "state_rename"
    if mode == "nest":
        ren = rename_keys(order, rng) if rng.random() < 0.5 else {k: k for k in order}
        w = rng.choice(NEST_WRAPS)
        while w in ctx:
            w += "_"
        out = {w: {ren[k]: state[k] for k in order}}
        out.update({k: state[k] for k in ctx})
        return out, "state_nest"
    if mode == "list":
        fk, vk = rng.choice((("field", "value"), ("name", "value"), ("key", "content")))
        return [{fk: k, vk: state[k]} for k in order], "state_list"
    return as_text([(k, state[k]) for k in order], rng.choice(TEXT_LAYOUTS)), "state_text"


def rename_questions(qids: list[str], rng: random.Random) -> dict[str, str]:
    if len(qids) == 1:
        return {qids[0]: rng.choice([n for n in QNAMES if n != qids[0]])}
    mode = rng.choice(("order_prefix", "case", "generic"))
    order = list(qids)
    rng.shuffle(order)
    if mode == "order_prefix":
        return {q: f"f{i:02d}_{q}"[:128] for i, q in enumerate(order, 1)}
    if mode == "generic":
        base = rng.choice(("q", "field_", "item_", "check_"))
        return {q: f"{base}{i}" for i, q in enumerate(order, 1)}
    style = rng.choice(("camel", "upper", "kebab", "title"))
    out, used = {}, set()
    for q in qids:
        nq = case_style(q, style) or q
        while nq in used:
            nq += "_"
        used.add(nq)
        out[q] = nq
    return out


def dedupe_options(q: dict, gold: str) -> dict:
    """v2 (review item 4): drop options whose text exactly duplicates another's (a duplicate of the gold's text made
    the gold ambiguous); the gold itself is always kept."""
    crit = q["criteria"]
    seen = {_norm_opt(crit[gold])} if crit.get(gold) is not None else set()
    out = {}
    for o, d in crit.items():
        if o == gold:
            out[o] = d
            continue
        k = _norm_opt(d)
        if d is not None and k in seen:
            continue
        seen.add(k)
        out[o] = d
    return {**q, "criteria": out} if len(out) >= 2 else q


def _norm_opt(d: Any) -> str:
    return " ".join(str(d).casefold().split())


def keys_named(rec: dict) -> bool:
    """v2 (review item 4): an instruction names a top-level state key ("For record_1: ..."): renaming / restructuring
    the state would leave the instruction pointing at a key that no longer exists."""
    st = rec["state"]
    if not isinstance(st, dict):
        return False
    text = "\n".join(q["instructions"] for q in rec["questions"].values() if isinstance(q.get("instructions"), str))
    return any(len(k) >= 3 and re.search(r"(?<![\w])" + re.escape(k) + r"(?![\w])", text) for k in st)


def variant(base: dict, j: int, seed: int, inventories: dict[str, list[str]], salt: int = 0) -> dict:
    rng = random.Random(f"bschema:{seed}:{base['id']}:{j}:{salt}")
    r = copy.deepcopy(base)
    ops: list[str] = []
    aug = r.get("aug") or {}
    inj = aug.get("injection") or {}
    restricted = bool(inj) or bool(r.get("untrusted_fields"))
    multi = len(r["questions"]) > 1
    for qid in list(r["questions"]):
        q, gold = r["questions"][qid], str(r["labels"][qid])
        if restricted:
            if qid != inj.get("question"):
                q2, op = paraphrase(q.get("instructions"), q["type"], rng)
                if op:
                    q = {**q, "instructions": q2}
                    ops.append(op)
            r["questions"][qid] = q
            continue
        if GEN["version"] >= 2 and q["type"] == "choice":
            k0 = len(q["criteria"])
            q = dedupe_options(q, gold)
            if len(q["criteria"]) < k0:
                ops.append("dedupe_options")
        ids = [str(o) for o in q["criteria"]] if q["type"] == "choice" else []
        refd = ids_referenced(r, ids, q.get("criteria") if q["type"] == "choice" else None) if ids else False
        if q["type"] in ("noul", "choice") and not refd and rng.random() < 0.3:
            sw = switch_type(q, gold, rng)
            if sw:
                q, gold = sw
                ops.append(f"type_to_{q['type']}")
                ids = [str(o) for o in q.get("criteria") or {}] if q["type"] == "choice" else []
                refd = ids_referenced(r, ids, q.get("criteria") if q["type"] == "choice" else None) if ids else False
        if q["type"] == "choice" and not refd:
            if not multi and r["source"] in INTENT_SOURCES and inventories.get(r["source"]) and rng.random() < 0.35:
                e = expand(q, inventories[r["source"]], rng)
                if e:
                    q = e
                    ops.append("k_expand")
            elif not multi and rng.random() < 0.35:
                s = shrink(q, gold, rng)
                if s:
                    q = s
                    ops.append("k_shrink")
            style = rng.choice(ID_STYLES)
            if any(o.startswith("__add_") for o in q["criteria"]) and style == "keep":
                style = "letters"
            q, gold = relabel(q, gold, rng, style)
            ops.append(f"ids:{style}")
        if q["type"] == "score" and rng.random() < 0.3:
            ins = q.get("instructions") if isinstance(q.get("instructions"), str) else ""
            if not re.search(r"\d", ins):
                q = {**q, "criteria": list(reversed(q["criteria"]))}
                gold = str(len(q["criteria"]) - 1 - int(gold))
                ops.append("scale_reverse")
        if rng.random() < 0.75:
            q2, op = paraphrase(q.get("instructions"), q["type"], rng)
            if op:
                q = {**q, "instructions": q2}
                ops.append(op)
        r["questions"][qid] = q
        r["labels"][qid] = gold
    if not restricted and rng.random() < 0.6:
        ren = rename_questions(list(r["questions"]), rng)
        r["questions"] = {ren[k]: v for k, v in r["questions"].items()}
        r["labels"] = {ren[k]: v for k, v in r["labels"].items()}
        ops.append("qid_rename")
    if not restricted and rng.random() < 0.8 and not (GEN["version"] >= 2 and keys_named(r)):
        st, op = transform_state(r["state"], rng)
        if op:
            r["state"] = st
            ops.append(op)
    root = sorted(root_items(base))[0]
    vid = f"{base['id']}~view:bs{j}" if "~view:" not in base["id"] else f"{base['id']}-bs{j}"
    view = aug.get("b1_view")
    aug = {k: v for k, v in aug.items() if k != "b1_view"}
    aug["b1_view"] = {"kind": "schema", "parent_id": base.get("aug", {}).get("b1_view", {}).get("parent_id", base["id"]),
                      "base_id": base["id"], **({"base_view": view} if view else {})}
    aug["schema_synth"] = {"ops": ops, "variant": j, "salt": salt, "seed": seed, "root": root}
    r["aug"] = aug
    r["id"] = vid
    return r


