def gz_text(path: Path):
    """Deterministic gzip text writer (mtime 0, as data.b1.write_draw)."""
    import io
    return io.TextIOWrapper(gzip.GzipFile(path, "wb", mtime=0), encoding="utf-8", newline="\n")


def read_gz(path: Path) -> Iterator[str]:
    with gzip.open(path, "rt", encoding="utf-8") as fh:
        for line in fh:
            if line.strip():
                yield line.rstrip("\n")


