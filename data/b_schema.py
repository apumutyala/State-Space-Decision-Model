def candidates(n: int, seed: int, work: Path, extra_pool: str | None, extra_pointer: str | None,
               extra_quota: int, log=print, limit: int | None = None, mix: str = "v1",
               base_pool: str | None = None, base_pointer: str | None = None) -> dict:
    """P1 + P2 bases -> variants (checked) -> ``work/candidates.jsonl.gz`` + ``work/candidates.meta.json``."""
    from .b1 import exclusion_sets, native_index, item_key

    GEN["version"] = SCHEMA_VERSION[mix]
    work.mkdir(parents=True, exist_ok=True)
    out_path = work / "candidates.jsonl.gz"
    if out_path.exists():
        raise SystemExit(f"refusing to overwrite {out_path} (move it to scratch first)")
    p1_dir, p1_ident = p1_files()
    ex = exclusion_sets()
    chk = Checker(ex)
    log("checker ready", chk.index["n_rows"], "index rows")
    # ---- pass 0: P1 roots, per-source counts, intent inventories
    p1_roots: set[str] = set()
    p1_ids: set[str] = set()
    src_items: collections.Counter = collections.Counter()
    inventories: dict[str, set[str]] = collections.defaultdict(set)
    for line in read_gz(p1_dir / "records.jsonl.gz"):
        r = json.loads(line)
        its = root_items(r)
        p1_roots |= its
        p1_ids.add(r["id"])
        src_items[mix_key(r, mix)] += 1
        from train.cohort import record_content_hash
        from .b1 import dedup_keys
        chk.content.add(h64(record_content_hash(r)))
        for kk in dedup_keys(r):  # P2 bases colliding with a P1 item's text are near-duplicates of it
            chk.text_owner.setdefault(h64(kk), h64(sorted(its)[0]))
        if r["source"] in INTENT_SOURCES and len(r["questions"]) == 1:
            q = next(iter(r["questions"].values()))
            if q["type"] == "choice":
                inventories[r["source"]] |= {str(d) for d in q["criteria"].values() if isinstance(d, str)}
    v3_mix = dict(src_items)  # v1 weights (the v3 draw's own mix); v2 uses MIX_V2
    weights = dict(v3_mix) if mix == "v1" else dict(MIX_V2)
    # ---- pass 1: P2 eligibility (150k + supplement natives whose item is new), same checks as the variants
    idx, nat_ident = native_index(config.BUILD_DIR)
    p2_ok: dict[str, str] = {}
    seen_items = set(p1_roots)
    by_src = collections.defaultdict(list)
    for rid, e in idx.items():
        by_src[e["src"]].append(rid)
    for src_file, ids in sorted(by_src.items()):
        want = set(ids)
        for line in read_gz(Path(src_file)):
            r = json.loads(line)
            if r["id"] not in want:
                continue
            its = root_items(r)
            if limit and len(p2_ok) >= limit:
                break
            if mix_key(r, mix) not in weights:  # e.g. 'mixed' multi-item rows: multi-question records are Agent C's
                chk.reasons["P2:" + r["source"]]["source_not_in_mix"] += 1
                continue
            if its & seen_items or r["id"] in ex["ids"]:
                chk.reasons["P2:" + r["source"]]["dup_or_cohort_item"] += 1
                continue
            if chk.accept(r, "P2:" + r["source"], h64(sorted(its)[0])):
                seen_items |= its
                p2_ok[r["id"]] = src_file
                src_items[mix_key(r, mix)] += 1
                if r["source"] in INTENT_SOURCES and len(r["questions"]) == 1:
                    q = next(iter(r["questions"].values()))
                    if q["type"] == "choice":
                        inventories[r["source"]] |= {str(d) for d in q["criteria"].values() if isinstance(d, str)}
    log("P2 eligible", len(p2_ok))
    # ---- pass 1b: P4 base pool (a pointer-pinned B1-format draw, e.g. b1-pool-v2x): new items, or more rows of items
    # P1 already has (another view of the same source item; the select stage caps rows per item at MAX_REUSE)
    p4_ok: set[str] = set()
    p4_ident = None
    if base_pool:
        from train.train_set import read_pointer, verify_files
        ptr4 = read_pointer(base_pointer)
        p4_ident = {"dir": base_pool, "pointer": base_pointer, "pointer_sha256": ptr4["_pointer_sha256"],
                    "files": verify_files(base_pool, ptr4)}
        for line in read_gz(Path(base_pool) / "records.jsonl.gz"):
            r = json.loads(line)
            key = mix_key(r, mix)
            if r["id"] in p1_ids or r["id"] in p2_ok:
                chk.reasons["P4:" + key]["same_record_in_p1_p2"] += 1
                continue
            if key not in weights:
                chk.reasons["P4:" + key]["not_in_mix"] += 1
                continue
            if chk.accept(r, "P4:" + key, h64(sorted(root_items(r))[0])):
                p4_ok.add(r["id"])
                src_items[key] += 1
        log("P4 eligible", len(p4_ok))
    # ---- plan: per-source targets from the v3 mix, scaled to n minus the extra pool's quota
    n_synth = n - (extra_quota if extra_pool else 0)
    tot = sum(weights.values())
    target = {s: n_synth * c / tot for s, c in weights.items()}
    #: expected variants per item of each source (fractional; each item gets floor or floor+1 by a hash of its root)
    per_item = {s: min(float(MAX_REUSE), SLACK * target[s] / src_items[s]) for s in target if src_items.get(s)}
    if mix == "v2":  # review item 5: new items over more variants; small families get at most 2 variants per item
        per_item = {s: min(v, SLACK * (V2_SMALL_MAX if src_items[s] < V2_SMALL_ITEMS else V2_MAX)) for s, v in per_item.items()}
    inv = {s: sorted(v) for s, v in inventories.items()}
    # ---- pass 2: variants
    n_out = collections.Counter()
    ops_count = collections.Counter()
    t0 = __import__("time").time()
    with gzip.open(out_path, "wt", encoding="utf-8") as out:
        def emit(base: dict, origin: str):
            s = mix_key(base, mix)
            its = root_items(base)
            ih = h64(sorted(its)[0])
            r_s = per_item.get(s, 0.0)
            want_v = int(r_s) + (1 if (ih % 100003) / 100003 < r_s - int(r_s) else 0)
            from train.cohort import record_content_hash
            chk.content.add(h64(record_content_hash(base)))  # a variant identical to its base is a duplicate
            # fractional: spread so that the source's expected candidates ~ SLACK * target
            got = 0
            for j in range(want_v):
                for salt in range(3):
                    v = variant(base, j, seed, inv, salt)
                    if chk.accept(v, f"{origin}:{s}", ih):
                        out.write(canonical(v) + "\n")
                        n_out[s] += 1
                        ops_count.update(o.split(":")[0] if not o.startswith("ids:") else o for o in v["aug"]["schema_synth"]["ops"])
                        got += 1
                        break
            return got

        k = 0
        for line in read_gz(p1_dir / "records.jsonl.gz"):
            if limit and k >= limit:
                break
            emit(json.loads(line), "P1")
            k += 1
            if k % 10000 == 0:
                log(f"P1 {k} bases, {sum(n_out.values())} candidates, {__import__('time').time() - t0:.0f}s")
        by_file = collections.defaultdict(set)
        for rid, f in p2_ok.items():
            by_file[f].add(rid)
        for f, want in sorted(by_file.items()):
            for line in read_gz(Path(f)):
                r = json.loads(line)
                if r["id"] in want:
                    emit(r, "P2")
                    k += 1
                    if k % 10000 == 0:
                        log(f"P2 {k} bases, {sum(n_out.values())} candidates")
        if base_pool:
            for line in read_gz(Path(base_pool) / "records.jsonl.gz"):
                r = json.loads(line)
                if r["id"] in p4_ok:
                    emit(r, "P4")
                    k += 1
                    if k % 10000 == 0:
                        log(f"P4 {k} bases, {sum(n_out.values())} candidates")
        extra_ident = None
        if extra_pool:
            from train.train_set import read_pointer, verify_files
            ptr = read_pointer(extra_pointer)
            extra_ident = {"dir": extra_pool, "pointer": extra_pointer, "pointer_sha256": ptr["_pointer_sha256"],
                           "files": verify_files(extra_pool, ptr)}
            reuse = collections.Counter()
            for line in read_gz(Path(extra_pool) / "records.jsonl.gz"):
                r = json.loads(line)
                its = root_items(r)
                if any(reuse[i] >= MAX_REUSE for i in its):
                    chk.reasons["P3"]["item_reuse_cap"] += 1
                    continue
                if chk.accept(r, "P3", h64(sorted(its)[0])):
                    r.setdefault("aug", {})["schema_synth"] = {"ops": ["extra_pool_passthrough"], "pool": "P3"}
                    out.write(canonical(r) + "\n")
                    n_out["P3:extra"] += 1
                    reuse.update(its)
    meta = {"seed": seed, "n_target": n, "n_synth_target": n_synth, "max_reuse": MAX_REUSE, "slack": SLACK,
            "p1": p1_ident, "p2": {"native": nat_ident, "eligible": len(p2_ok)}, "p3": extra_ident,
            "extra_quota": extra_quota if extra_pool else 0,
            "mix": mix, "weights": weights, "no_spill": sorted(NO_SPILL_V2) if mix == "v2" else [],
            "p4": {"pool": p4_ident, "eligible": len(p4_ok)},
            "v3_mix": v3_mix, "items_per_source": dict(src_items), "target_per_source": target,
            "variants_per_item": per_item, "candidates_per_source": dict(n_out), "ops": dict(ops_count),
            "checker": {"reasons": {k: dict(v) for k, v in chk.reasons.items()},
                        "index_item_text_examples": chk.hit_examples, "guard": chk.guard_identity,
                        "exclusions": ex["identity"]},
            "generator_spec": GENERATOR_SPEC,
            "candidates_uncompressed_sha256": None}
    from train.train_set import uncompressed_sha256
    meta["candidates_uncompressed_sha256"] = uncompressed_sha256(out_path)
    (work / "candidates.meta.json").write_text(json.dumps(meta, indent=1, default=str) + "\n", encoding="utf-8")
    return meta


def candidate_lines(work: Path, meta: dict) -> Iterator[str]:
    """candidates.jsonl.gz, then (if appended) candidates-extra.jsonl.gz, each verified against the meta."""
    yield from read_gz(work / "candidates.jsonl.gz")
    ex = meta.get("extra_appended")
    if ex:
        from train.train_set import uncompressed_sha256
        if uncompressed_sha256(work / "candidates-extra.jsonl.gz") != ex["candidates_extra_uncompressed_sha256"]:
            raise SystemExit("candidates-extra drifted from the meta")
        yield from read_gz(work / "candidates-extra.jsonl.gz")


def append_extra(work: Path, extra_pool: str, extra_pointer: str, quota: int, log=print,
                 limit: int | None = None) -> dict:
    """P3 after the fact: Agent C's pointer-pinned draw, checked against every candidate already built (exact content,
    key-free near-duplicates across items) plus all the per-row checks, written to ``candidates-extra.jsonl.gz``
    (unchanged records, ``aug.schema_synth.pool = "P3"``); the select stage then takes ``quota`` rows of it."""
    from train.cohort import record_content_hash
    from train.train_set import read_pointer, uncompressed_sha256, verify_files
    from .b1 import dedup_keys, exclusion_sets

    meta_p = work / "candidates.meta.json"
    meta = json.loads(meta_p.read_text(encoding="utf-8"))
    if uncompressed_sha256(work / "candidates.jsonl.gz") != meta["candidates_uncompressed_sha256"]:
        raise SystemExit("candidates drifted from their meta")
    out_path = work / "candidates-extra.jsonl.gz"
    if out_path.exists() or meta.get("extra_appended"):
        raise SystemExit("extra pool already appended (move the file to scratch first)")
    ptr = read_pointer(extra_pointer)
    ident = {"dir": extra_pool, "pointer": extra_pointer, "pointer_sha256": ptr["_pointer_sha256"],
             "files": verify_files(extra_pool, ptr), "quota": quota}
    GEN["version"] = SCHEMA_VERSION[meta.get("mix", "v1")]
    chk = Checker(exclusion_sets())
    p1_dir, _ = p1_files()
    for path in (p1_dir / "records.jsonl.gz", work / "candidates.jsonl.gz"):
        for line in read_gz(path):
            r = json.loads(line)
            ih = h64(sorted(root_items(r))[0])
            chk.content.add(h64(record_content_hash(r)))
            for kk in dedup_keys(r):
                chk.text_owner.setdefault(h64(kk), ih)
    reuse = collections.Counter()
    n = 0
    with gz_text(out_path) as out:
        for line in read_gz(Path(extra_pool) / "records.jsonl.gz"):
            if limit and n >= limit:  # the pool's own (seeded) order; only what can be drawn is token-checked
                break
            r = json.loads(line)
            its = root_items(r)
            if any(reuse[i] >= MAX_REUSE for i in its):
                chk.reasons["P3"]["item_reuse_cap"] += 1
                continue
            if chk.accept(r, "P3", h64(sorted(its)[0])):
                r.setdefault("aug", {})["schema_synth"] = {"ops": ["extra_pool_passthrough"], "pool": "P3"}
                out.write(canonical(r) + "\n")
                reuse.update(its)
                n += 1
    ident["limit"] = limit
    ident["n_candidates"] = n
    ident["reasons"] = {k: dict(v) for k, v in chk.reasons.items()}
    ident["candidates_extra_uncompressed_sha256"] = uncompressed_sha256(out_path)
    meta["extra_appended"] = ident
    meta_p.write_text(json.dumps(meta, indent=1, default=str) + "\n", encoding="utf-8")
    return ident


