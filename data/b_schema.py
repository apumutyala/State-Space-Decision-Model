    if a.stage == "candidates":
        if a.extra_pool and not a.extra_pointer:
            raise SystemExit("--extra-pool needs --extra-pointer")
        meta = candidates(a.n, a.seed, work, a.extra_pool, a.extra_pointer, a.extra_quota,
                          log=lambda *x: print(*x, flush=True), limit=a.smoke, mix=a.mix,
                          base_pool=a.base_pool, base_pointer=a.base_pointer)
        print(json.dumps({k: meta[k] for k in ("candidates_per_source", "ops")}, indent=1))
        return 0
    rep = select(a.n, work, build, log=lambda *x: print(*x, flush=True),
                 extra_quota=a.extra_quota if a.extra_quota else None, heldout_json=a.heldout_json, dry=a.dry)
    if rep.get("dry"):
        print(json.dumps(rep, indent=1, default=str))
        return 0
    commit = subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True,
                            cwd=config.REPO_ROOT).stdout.strip()
    ptr = write_pointer(build, rep, commit)
    rdir = Path(a.receipt) if a.receipt else config.REPO_ROOT / "receipts" / "2026-10-08-B1-schema" / build
    rdir.mkdir(parents=True, exist_ok=True)
    meta = json.loads((work / "candidates.meta.json").read_text(encoding="utf-8"))
    (rdir / "build-report.json").write_text(json.dumps({"select": rep, "candidates": meta}, indent=1, default=str) + "\n",
                                            encoding="utf-8")
    print(json.dumps({"pointer": str(ptr), "n": rep["n_records"], "reuse": rep["reuse"], "tokens": rep["tokens"]},
                     indent=1))
    return 0


