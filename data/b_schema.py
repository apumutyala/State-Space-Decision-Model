def learn_polarity(path: Path) -> dict[str, bool]:
    """option description -> positive?, from two-option questions with semantic positive/negative ids (and noul
    criteria) of the base draw, so re-styled ids are still classified by their description"""
    pol: dict[str, bool] = {}
    for line in read_gz(path):
        r = json.loads(line)
        for q in r["questions"].values():
            c = q.get("criteria")
            if q["type"] == "choice" and isinstance(c, dict) and len(c) == 2:
                ids = {_normt(o): d for o, d in c.items()}
                if any(i in POS_IDS for i in ids) and any(i in NEG_IDS for i in ids):
                    for i, d in ids.items():
                        if d is not None:
                            pol.setdefault(_normt(d), i in POS_IDS)
            if q["type"] == "noul" and isinstance(c, dict):
                for k, d in c.items():
                    pol.setdefault(_normt(d), k == "true")
    return pol


def polarity(q: dict, lab: Any, pol: dict[str, bool]) -> bool | None:
    """True / False = a binary question with a positive / negative gold; None = not binary"""
    if q["type"] == "noul":
        return str(lab).lower() == "true"
    c = q.get("criteria")
    if q["type"] != "choice" or not isinstance(c, dict) or len(c) != 2:
        return None
    ids = {_normt(k) for k in c}
    if any(i in POS_IDS for i in ids) and any(i in NEG_IDS for i in ids):
        return _normt(lab) in POS_IDS
    ps = {str(k): (pol.get(_normt(d)) if d is not None else None) for k, d in c.items()}
    if None in ps.values() or len(set(ps.values())) != 2:
        return None
    return bool(ps[str(lab)])


def plan_items_v2(weights: dict, kstats: dict, avail: dict, n_records: int, log=print) -> tuple[dict, dict]:
    """Record quotas per key so that ITEM shares follow ``weights`` with: membership / verify views <= 5 % of items
    combined, the aggregate no-share of binary items <= 60 % (no-heavy binary keys scaled down; per-key base rates
    untouched), glaive never above its weight share, and shortfalls spilled only to keys that are not no-heavy."""
    keys = [k for k in weights if avail.get(k, 0) > 0 and kstats.get(k, {}).get("rows")]
    st = {k: {"items": kstats[k].get("items", 0) / kstats[k]["rows"],
              "bin": kstats[k].get("bin", 0) / max(1, kstats[k].get("items", 0)),
              "yes": kstats[k].get("yes", 0) / max(1, kstats[k].get("bin", 0))} for k in keys}
    tot = sum(weights[k] for k in keys)
    share = {k: weights[k] / tot for k in keys}
    glaive_cap = {k: share[k] for k in NO_SPILL_V2 if k in share}
    noheavy = {k for k in keys if st[k]["bin"] > 0.5 and st[k]["yes"] < 0.4}
    locked = set(MV_KEYS) | noheavy | set(NO_SPILL_V2)

    def norm_():
        """glaive keys stay at (at most) their weight share; every other key is renormalised to the remainder"""
        for k, c in glaive_cap.items():
            share[k] = min(share[k], c)
        g = sum(share[k] for k in glaive_cap)
        t = sum(v for k, v in share.items() if k not in glaive_cap)
        for k in share:
            if k not in glaive_cap:
                share[k] *= (1 - g) / t

    def no_share():
        b = sum(share[k] * st[k]["bin"] for k in keys)
        return sum(share[k] * st[k]["bin"] * (1 - st[k]["yes"]) for k in keys) / max(1e-9, b)

    # records. Locked keys (glaive, membership / verify views, no-heavy binary keys) get share_k * T items, T = the
    # draw's total items (self-consistent fixed point), so their ITEM share never grows when other keys run out;
    # unlocked keys get share_k * S items with S solved (bisection) so that the records sum to n_records; every key
    # is clamped to its availability.
    def records(S: float, T: float) -> dict:
        return {k: min(avail[k], share[k] * (T if k in locked else S) / st[k]["items"]) for k in keys}

    def alloc() -> dict:
        T = float(n_records)
        rec = {}
        for _ in range(60):
            lo, hi = 0.0, 1e9
            for _ in range(100):
                mid = (lo + hi) / 2
                if sum(records(mid, T).values()) < n_records:
                    lo = mid
                else:
                    hi = mid
            rec = records(hi, T)
            T_new = sum(rec[k] * st[k]["items"] for k in keys)
            if abs(T_new - T) < 1:
                break
            T = T_new
        return rec

    def achieved(rec: dict) -> tuple[float, float, dict]:
        items = {k: rec[k] * st[k]["items"] for k in keys}
        ti = sum(items.values())
        b = sum(items[k] * st[k]["bin"] for k in keys)
        no = sum(items[k] * st[k]["bin"] * (1 - st[k]["yes"]) for k in keys) / max(1e-9, b)
        mv = sum(items.get(k, 0) for k in MV_KEYS) / max(1e-9, ti)
        return no, mv, {k: items[k] / ti for k in keys}

    # constraints on what is ACHIEVED (after availability): membership / verify <= 5 % of items; binary no-share <= 60 %
    # by scaling no-heavy keys down, never below their FLOOR_V2 item share (eval-regression families)
    rec = alloc()
    for _ in range(300):
        no, mv, ish = achieved(rec)
        changed = False
        if mv > MV_MAX_ITEM_SHARE:
            for k in MV_KEYS:
                if k in share:
                    share[k] *= 0.95
            changed = True
        if no > MAX_NO_SHARE:
            for k in noheavy:
                if k not in MV_KEYS and ish.get(k, 0) > FLOOR_V2.get(k, 0.0) * 1.02:
                    share[k] *= 0.95
                    changed = True
        if not changed:
            break
        norm_()
        rec = alloc()
    q = {k: int(rec[k]) for k in keys}
    diff = n_records - sum(q.values())
    spill = sorted((k for k in keys if k not in locked and q[k] < avail[k]), key=lambda k: -(avail[k] - q[k]))
    i = 0
    while diff > 0 and spill and i < 10 * len(spill) + n_records:
        k = spill[i % len(spill)]
        if q[k] < avail[k]:
            q[k] += 1
            diff -= 1
        i += 1
    items = {k: q[k] * st[k]["items"] for k in q}
    ti = sum(items.values())
    b = sum(items[k] * st[k]["bin"] for k in q)
    plan = {"item_share_planned": {k: round(items[k] / ti, 4) for k in sorted(q, key=lambda k: -items[k])},
            "planned_items": round(ti), "binary_no_share_planned": round(
                sum(items[k] * st[k]["bin"] * (1 - st[k]["yes"]) for k in q) / max(1, b), 4),
            "mv_item_share_planned": round(sum(items.get(k, 0) for k in MV_KEYS) / ti, 4),
            "key_stats": st, "no_heavy_keys": sorted(noheavy), "locked_keys": sorted(locked)}
    log("v2 item plan", json.dumps({k: plan[k] for k in ("planned_items", "binary_no_share_planned",
                                                        "mv_item_share_planned")}))
    return q, plan


def select(n: int, work: Path, build: str, max_t: int = 2048, log=print, extra_quota: int | None = None,
           heldout_json: str | None = None, dry: bool = False) -> dict:
    """Candidates + token lengths -> the n-row draw (per-source targets, fewest-variants-first, reuse cap)."""
    from train.cohort import record_content_hash
    from train.train_set import uncompressed_sha256

    meta = json.loads((work / "candidates.meta.json").read_text(encoding="utf-8"))
    if uncompressed_sha256(work / "candidates.jsonl.gz") != meta["candidates_uncompressed_sha256"]:
        raise SystemExit("candidates drifted from their meta")
    lens: dict[str, dict] = {}
    for p in sorted(work.glob("lens-*.jsonl")):
        for line in p.read_text(encoding="utf-8").splitlines():
            e = json.loads(line)
            lens[e["id"]] = e
    # pass 1: eligible ids by source, with root item and variant index
    elig: dict[str, list[tuple[str, str, int]]] = collections.defaultdict(list)
    kstats: dict[str, collections.Counter] = collections.defaultdict(collections.Counter)
    pol = learn_polarity(p1_files()[0] / "records.jsonl.gz") if meta.get("mix") == "v2" else {}
    drop = collections.Counter()
    tok = {"v2f": [], "v3w": []}
    af = None
    if meta.get("mix") == "v2" or heldout_json:  # operator rule: no eval attack template text in training rows
        if not heldout_json:
            raise SystemExit("v2 select needs --heldout-json (the pinned heldout_v1 templates copy)")
        from .attack_filter import AttackFilter
        af = AttackFilter(heldout_json)
    n_cand = 0
    for line in candidate_lines(work, meta):
        r = json.loads(line)
        n_cand += 1
        e = lens.get(r["id"])
        if e is None:
            drop["no_tokcheck"] += 1
            continue
        if "error" in e:
            drop["render_error"] += 1
            continue
        if e["t_v2f"] > max_t or e["t_v3w"] > max_t:
            drop["over_2048"] += 1
            continue
        if e.get("cont", 0) > 16:
            drop["continuation_over_16"] += 1
            continue
        if af is not None:
            hit = af.hit(r)
            if hit:
                drop[f"attack:{hit[1]}/{hit[2]}/{hit[0]}"] += 1
                continue
        ss = r.get("aug", {}).get("schema_synth", {})
        src = "P3:extra" if ss.get("pool") == "P3" else mix_key(r, meta.get("mix", "v1"))
        elig[src].append((r["id"], ss.get("root") or sorted(root_items(r))[0], ss.get("variant", 0)))
        if pol:
            ks = kstats[src]
            ks["rows"] += 1
            for qid, q in r["questions"].items():
                ks["items"] += 1
                pz = polarity(q, r["labels"][qid], pol)
                if pz is not None:
                    ks["bin"] += 1
                    ks["yes"] += int(pz)
    if n_cand != len(lens):
        raise SystemExit(f"token check covers {len(lens)} ids, candidates file has {n_cand}: run every shard")
    if meta.get("mix") == "v2":  # review item 5: at most 2 (small key) / 3 rows per source item per key, fewest first
        items = meta["items_per_source"]
        for s, rows in elig.items():
            if s == "P3:extra":
                continue
            cap = V2_SMALL_MAX if items.get(s, 0) < V2_SMALL_ITEMS else V2_MAX
            rows.sort(key=lambda x: (x[2], sha(f"{meta['seed']}:{x[0]}")))
            per = collections.Counter()
            kept = []
            for x in rows:
                if per[x[1]] < cap:
                    per[x[1]] += 1
                    kept.append(x)
                else:
                    drop["per_item_cap_v2"] += 1
            elig[s] = kept
    weights = meta.get("weights") or meta["v3_mix"]
    no_spill = set(meta.get("no_spill") or [])
    tot = sum(weights.values())
    n_synth = meta["n_synth_target"]
    quota = {s: round(n_synth * c / tot) for s, c in weights.items()}
    if meta.get("extra_quota"):
        quota["P3:extra"] = meta["extra_quota"]
    elif meta.get("extra_appended"):
        quota["P3:extra"] = extra_quota if extra_quota is not None else meta["extra_appended"]["quota"]
        n_synth = n - quota["P3:extra"]
        quota.update({s: round(n_synth * c / tot) for s, c in weights.items()})
    # sources that cannot fill their quota spill to the others in proportion
    avail = {s: len(elig.get(s, [])) for s in quota}
    item_plan = None
    if meta.get("mix") == "v2":
        n_syn = n - quota.get("P3:extra", 0)
        qv2, item_plan = plan_items_v2(weights, kstats, avail, n_syn, log=log)
        item_plan["capacity_records"] = sum(qv2.values())
        if dry:
            return {"dry": True, "n_syn_asked": n_syn, "capacity_records": sum(qv2.values()), "quotas": qv2,
                    "item_plan": {k: v for k, v in item_plan.items() if k != "key_stats"}, "dropped": dict(drop),
                    "kstats_P3": dict(kstats.get("P3:extra", {}))}
        if 0 < n_syn - sum(qv2.values()) <= max(10, n_syn // 1000):  # rounding at the capacity bound
            n = sum(qv2.values()) + quota.get("P3:extra", 0)
        elif sum(qv2.values()) != n_syn:
            raise SystemExit(f"v2 plan is capacity-bound at {sum(qv2.values())} synthetic records (asked {n_syn}): "
                             f"re-run with --n {sum(qv2.values()) + quota.get('P3:extra', 0)}")
        quota = {**{s: 0 for s in weights}, **qv2, **({"P3:extra": quota["P3:extra"]} if "P3:extra" in quota else {})}
    for _ in range(0 if item_plan else 5):
        short = sum(max(0, quota[s] - avail[s]) for s in quota)
        if short <= 0:
            break
        quota = {s: min(quota[s], avail[s]) for s in quota}
        room = {s: avail[s] - quota[s] for s in quota
                if avail[s] > quota[s] and s != "P3:extra" and s not in no_spill}
        rt = sum(room.values())
        for s in room:
            quota[s] += min(room[s], math.floor(short * room[s] / rt) + 1)
    diff = sum(quota.values()) - n
    for s in sorted(quota, key=lambda s: -quota[s]) if not item_plan else []:
        if diff == 0:
            break
        step = 1 if diff > 0 else -1
        if step < 0 and (quota[s] >= avail[s] or s in no_spill):
            continue
        quota[s] -= step
        diff -= step
    chosen: set[str] = set()
    reuse = collections.Counter()
    for s, q in quota.items():
        rows = elig.get(s, [])
        # fewest variants per item first: round-robin over items by variant index, ties by a seeded hash
        rows.sort(key=lambda x: (x[2], sha(f"{meta['seed']}:{x[0]}")))
        k = 0
        for rid, root, _ in rows:
            if k >= q:
                break
            if reuse[root] >= MAX_REUSE:
                continue
            chosen.add(rid)
            reuse[root] += 1
            k += 1
    if len(chosen) != n:
        raise SystemExit(f"selected {len(chosen)} != {n}; quotas {quota}")
    # pass 2: write the draw (sorted by id, the 150k set's convention)
    out_dir = config.BUILD_DIR / build
    if (out_dir / "records.jsonl.gz").exists():
        raise SystemExit(f"refusing to overwrite {out_dir}")
    out_dir.mkdir(parents=True, exist_ok=True)
    tmp = work / "chosen.unsorted.jsonl.gz"
    with gzip.open(tmp, "wt", encoding="utf-8") as fo:
        for line in candidate_lines(work, meta):
            rid = json.loads(line)["id"]
            if rid in chosen:
                fo.write(line + "\n")
    order = sorted(chosen)
    pos = {rid: i for i, rid in enumerate(order)}
    # external sort in chunks to bound RAM: bucket by sha prefix of position
    buckets = 32
    paths = [work / f"bucket-{b:02d}.jsonl" for b in range(buckets)]
    fhs = [open(p, "w", encoding="utf-8") for p in paths]
    for line in read_gz(tmp):
        rid = json.loads(line)["id"]
        fhs[pos[rid] * buckets // len(order)].write(line + "\n")
    for f in fhs:
        f.close()
    rec_h, man_h, con_h = hashlib.sha256(), hashlib.sha256(), hashlib.sha256()
    stats = Stats()
    with gz_text(out_dir / "records.jsonl.gz") as fr, gz_text(out_dir / f"{build}.manifest.jsonl.gz") as fm:
        content_rows = []
        for p in paths:
            lines = p.read_text(encoding="utf-8").splitlines()
            lines.sort(key=lambda x: json.loads(x)["id"])
            for line in lines:
                r = json.loads(line)
                fr.write(line + "\n")
                rec_h.update((line + "\n").encode("utf-8"))
                m = canonical({"family": r["family"], "id": r["id"], "sha256": sha(line), "source": r["source"]}) + "\n"
                fm.write(m)
                man_h.update(m.encode("utf-8"))
                content_rows.append(canonical({"content_sha256": record_content_hash(r), "id": r["id"]}) + "\n")
                stats.add(r, lens[r["id"]])
    with gz_text(out_dir / f"{build}.content.jsonl.gz") as fc:
        for c in content_rows:
            fc.write(c)
            con_h.update(c.encode("utf-8"))
    for p in paths + [tmp]:  # intermediate files: moved to the work dir's scratch, never deleted
        sc = work / "scratch-moved"
        sc.mkdir(exist_ok=True)
        p.replace(sc / p.name)
    rep = {"build": build, "n_records": len(order), "quotas": quota, "item_plan": item_plan,
           "attack_filter": af.identity if af is not None else None, "available": avail, "dropped": dict(drop),
           "n_candidates": n_cand, "reuse": reuse_stats(reuse), **stats.report(),
           "records_uncompressed_sha256": rec_h.hexdigest(), "manifest_uncompressed_sha256": man_h.hexdigest(),
           "content_map_uncompressed_sha256": con_h.hexdigest()}
    return rep


def reuse_stats(reuse: collections.Counter) -> dict:
    hist = collections.Counter(reuse.values())
    n_rows = sum(reuse.values())
    return {"source_items": len(reuse), "max_variants_per_item": max(reuse.values()),
            "rows_sharing_a_source_item_frac": round(sum(c for c in reuse.values() if c > 1) / n_rows, 4),
            "variants_per_item_hist": dict(sorted(hist.items()))}


class Stats:
    def __init__(self):
        self.by_source = collections.Counter()
        self.by_family = collections.Counter()
        self.ops = collections.Counter()
        self.ids = collections.Counter()
        self.qtypes = collections.Counter()
        self.kbin = collections.Counter()
        self.binary = collections.defaultdict(collections.Counter)
        self.gold_pos = collections.defaultdict(collections.Counter)
        self.t = {"t_v2f": [], "t_v3w": []}
        self.nq = collections.Counter()
        self.items = collections.defaultdict(set)
        self.rows_by_key = collections.Counter()

    def add(self, r: dict, e: dict):
        from decide.schema import canonical_options
        self.by_source[r["source"]] += 1
        self.by_family[r["family"]] += 1
        key = f"{r['source']}/{r['family']}"
        ss = r.get("aug", {}).get("schema_synth", {})
        self.items[key].add(ss.get("root") or sorted(root_items(r))[0])
        self.rows_by_key[key] += 1
        ops = r.get("aug", {}).get("schema_synth", {}).get("ops", [])
        for o in ops:
            self.ops["ids" if o.startswith("ids:") else o.split(":")[0]] += 1
            if o.startswith("ids:"):
                self.ids[o[4:]] += 1
        self.nq[min(len(r["questions"]), 10)] += 1
        for qid, q in r["questions"].items():
            self.qtypes[q["type"]] += 1
            opts = [o for o, _ in canonical_options(q)]
            k = len(opts)
            self.kbin["2" if k == 2 else "3-8" if k <= 8 else "9-16" if k <= 16 else "17-40" if k <= 40 else ">40"] += 1
            lab = str(r["labels"][qid])
            if q["type"] == "noul":
                self.binary[r["source"]]["true" if lab.lower() == "true" else "false"] += 1
            elif q["type"] == "choice" and k == 2 and {o.casefold() for o in opts} in ({"yes", "no"}, {"y", "n"}):
                self.binary[r["source"]]["true" if lab.casefold() in ("yes", "y") else "false"] += 1
            if q["type"] == "choice" and 2 <= k <= 16 and len(r["questions"]) == 1:
                self.gold_pos[k][opts.index(lab)] += 1
        for k in self.t:
            self.t[k].append(e[k])

    def report(self) -> dict:
        def pct(v, p):
            v = sorted(v)
            return v[min(len(v) - 1, int(p * len(v)))]
        gp = {}
        for k, c in sorted(self.gold_pos.items()):
            n = sum(c.values())
            if n >= 200:
                gp[k] = {"n": n, "max_rel_dev": round(max(abs(c[i] / n - 1 / k) * k for i in range(k)), 3)}
        return {"by_key": {k: {"rows": c, "unique_items": len(self.items[k]),
                               "rows_per_item": round(c / len(self.items[k]), 2)}
                           for k, c in self.rows_by_key.most_common()},
                "by_source": dict(self.by_source.most_common()), "by_family": dict(self.by_family.most_common()),
                "ops_rows": dict(self.ops.most_common()), "id_styles": dict(self.ids.most_common()),
                "question_types": dict(self.qtypes), "options_k": dict(self.kbin), "questions_per_record": dict(self.nq),
                "binary_true_rate_by_source": {s: round(c["true"] / max(1, sum(c.values())), 4)
                                               for s, c in sorted(self.binary.items())},
                "gold_canonical_position_uniformity": gp,
                "tokens": {k: {"p50": pct(v, .5), "p95": pct(v, .95), "p99": pct(v, .99), "max": max(v)}
                           for k, v in self.t.items()}}


